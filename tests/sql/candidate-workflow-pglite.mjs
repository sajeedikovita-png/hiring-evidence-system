// Isolated PostgreSQL behavior tests; never connects to a deployed database.
// Imports real membership access SQL. Entitlement is a controllable fixture stub,
// so these tests verify workflow enforcement, not the complete access lifecycle.
import fs from 'node:fs';
import assert from 'node:assert/strict';
const {PGlite}=await import(process.env.PGLITE_MODULE_PATH || '/tmp/hiring-pricing-db-test/node_modules/@electric-sql/pglite/dist/index.js');
const db=new PGlite();
const id=n=>`00000000-0000-0000-0000-${String(n).padStart(12,'0')}`;
await db.exec(`create role anon; create role authenticated; create schema auth;
create function auth.uid() returns uuid language sql as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
create table companies(id uuid primary key,status text, writable boolean default true);
create table recruiter_profiles(id uuid primary key,company_id uuid,user_id uuid,display_name text,status text,role text);
create table job_roles(id uuid primary key,company_id uuid,status text default 'open');
create table candidate_applications(id uuid primary key,company_id uuid,job_id uuid,created_at timestamptz default now());
create table human_review_decisions(id uuid primary key,reason text);

create function demo_workspace_is_writable(p uuid) returns boolean language sql security definer as $$select writable from companies where id=p$$;
insert into companies values('${id(1)}','active',true),('${id(2)}','active',true);
insert into recruiter_profiles values('${id(11)}','${id(1)}','${id(101)}','Recruiter A','active','recruiter'),('${id(12)}','${id(2)}','${id(102)}','Recruiter B','active','recruiter'),('${id(13)}','${id(1)}','${id(103)}','Disabled','disabled','recruiter');
insert into job_roles(id,company_id) values('${id(21)}','${id(1)}'),('${id(22)}','${id(2)}');
insert into candidate_applications(id,company_id,job_id) values('${id(31)}','${id(1)}','${id(21)}'),('${id(32)}','${id(2)}','${id(22)}');
insert into human_review_decisions values('${id(41)}','Preserve this human decision');
select set_config('request.jwt.claim.sub','${id(101)}',false);`);
const membership=fs.readFileSync('supabase/migrations/202609090001_workspace_access_hardening.sql','utf8');
await db.exec(membership.slice(membership.indexOf('create or replace function public.current_company_ids()'),membership.indexOf('-- Storage policies')));
await db.exec(fs.readFileSync('supabase/migrations/202609190004_candidate_workflow.sql','utf8'));
const q=async(sql,args=[]) => (await db.query(sql,args)).rows;
const fail=async(sql,args,error)=>assert.rejects(()=>q(sql,args),e=>e.message.includes(error));
const save='select update_candidate_workflow($1,$2,$3,$4,$5,$6) as result';
await db.exec('set role authenticated');
let rows=await q('select list_candidate_workflows($1) as result',[id(21)]);
assert.equal(rows[0].result.workflows[0].version,0);
assert.equal(rows[0].result.current_profile_id,id(11));
assert.equal(rows[0].result.reviewers.length,2);
await fail('select list_candidate_workflows($1)',[id(22)],'JOB_UNAVAILABLE');
await fail('select list_candidate_workflow_events($1)',[id(32)],'APPLICATION_UNAVAILABLE');
await fail(save,[id(32),'new',null,'',null,0],'APPLICATION_UNAVAILABLE');
await fail(save,[id(31),'invalid',null,'',null,0],'WORKFLOW_STAGE_INVALID');
await fail(save,[id(31),'new',id(12),'',null,0],'WORKFLOW_ASSIGNEE_INVALID');
await fail(save,[id(31),'new',id(13),'',null,0],'WORKFLOW_ASSIGNEE_INVALID');
await fail(save,[id(31),'new',null,'x'.repeat(501),null,0],'WORKFLOW_NEXT_ACTION_TOO_LONG');
await fail(save,[id(31),'new',null,'','infinity',0],'WORKFLOW_DUE_AT_INVALID');
rows=await q(save,[id(31),'interview',id(11),'  Confirm project  ','2026-10-01T12:00:00Z',0]);
assert.equal(rows[0].result.version,1);
assert.equal(rows[0].result.next_action,'Confirm project');
await fail(save,[id(31),'closed',null,'',null,0],'WORKFLOW_VERSION_CONFLICT');
await q(save,[id(31),'interview',id(11),'Confirm project','2026-10-01T12:00:00Z',1]);
assert.equal((await q('select list_candidate_workflow_events($1) as result',[id(31)]))[0].result.length,1,'no-op saves create no activity');
await q(save,[id(31),'closed',null,'',null,1]);
rows=await q('select list_candidate_workflow_events($1) as result',[id(31)]);
assert.equal(rows[0].result.length,2);
assert.equal(rows[0].result[0].actor_profile_id,id(11));
assert.equal(rows[0].result[0].actor_name,'Recruiter A');
await fail('update candidate_workflow_events set actor_name=$1',['Forged'],'permission denied');
await fail('delete from candidate_workflow_events',[],'permission denied');
await fail('update candidate_workflows set stage=$1',['new'],'permission denied');
await db.exec('reset role');
assert.equal((await q('select reason from human_review_decisions'))[0].reason,'Preserve this human decision');
await db.exec(`update companies set writable=false where id='${id(1)}'; set role authenticated;`);
assert.equal((await q('select list_candidate_workflows($1) as result',[id(21)]))[0].result.can_edit,false);
await fail(save,[id(31),'new',null,'',null,2],'WORKFLOW_WRITE_ACCESS_REQUIRED');
await db.exec(`reset role; update companies set status='paused' where id='${id(1)}'; set role authenticated;`);
await fail('select list_candidate_workflows($1)',[id(21)],'JOB_UNAVAILABLE');
assert.equal((await q('select * from candidate_workflows')).length,0);
await db.exec(`reset role; update companies set status='active' where id='${id(1)}'; select set_config('request.jwt.claim.sub','${id(102)}',false); set role authenticated;`);
assert.equal((await q('select * from candidate_workflows')).length,0);
assert.equal((await q('select * from candidate_workflow_events')).length,0);
await db.exec(`reset role; select set_config('request.jwt.claim.sub','${id(101)}',false); update companies set writable=null where id='${id(1)}'; set role authenticated;`);
assert.equal((await q('select list_candidate_workflows($1) as result',[id(21)]))[0].result.can_edit,false);
await fail(save,[id(31),'new',null,'',null,2],'WORKFLOW_WRITE_ACCESS_REQUIRED');
await db.exec(`reset role; update companies set writable=true where id='${id(1)}'; update recruiter_profiles set status='disabled' where id='${id(11)}'; set role authenticated;`);
await fail('select list_candidate_workflows($1)',[id(21)],'JOB_UNAVAILABLE');
await fail(save,[id(31),'new',null,'',null,2],'APPLICATION_UNAVAILABLE');
await db.exec(`reset role; update recruiter_profiles set status='active',role='admin' where id='${id(11)}'; set role authenticated;`);
assert.equal((await q(save,[id(31),'new',null,'Admin follow-up',null,2]))[0].result.version,3);
await db.exec(`reset role; update recruiter_profiles set role='hiring_manager' where id='${id(11)}'; set role authenticated;`);
assert.equal((await q(save,[id(31),'evidence_review',null,'Manager follow-up',null,3]))[0].result.version,4);
await db.exec('reset role; set role anon');
await fail('select list_candidate_workflows($1)',[id(21)],'permission denied');
await fail('select list_candidate_workflow_events($1)',[id(31)],'permission denied');
await fail(save,[id(31),'new',null,'',null,4],'permission denied');
await db.exec(`reset role; update job_roles set status='closed' where id='${id(21)}';`);
assert.equal((await q('select stage from candidate_workflows where application_id=$1',[id(31)]))[0].stage,'evidence_review','role closure preserves candidate stage');
await db.exec(`delete from recruiter_profiles where id='${id(11)}';`);
rows=await q('select actor_profile_id,actor_name from candidate_workflow_events where application_id=$1',[id(31)]);
assert.equal(rows.length,4);
assert.ok(rows.every(row=>row.actor_profile_id===null && row.actor_name==='Recruiter A'),'actor removal preserves attributable historical display name');
