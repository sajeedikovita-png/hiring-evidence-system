// Isolated PostgreSQL behavior tests; never connects to a deployed database.
// Imports real membership access SQL. Entitlement is a controllable fixture stub,
// so these tests verify workflow enforcement, not the complete access lifecycle.
import fs from 'node:fs';
import assert from 'node:assert/strict';
const {PGlite}=await import(process.env.PGLITE_MODULE_PATH || '/tmp/hiring-pricing-db-test/node_modules/@electric-sql/pglite/dist/index.js');
const db=new PGlite();
const id=n=>`00000000-0000-0000-0000-${String(n).padStart(12,'0')}`;
await db.exec(`create role anon; create role authenticated; create schema auth;
create function auth.uid() returns uuid language sql as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
create table companies(id uuid primary key,status text, writable boolean default true);
create table recruiter_profiles(id uuid primary key,company_id uuid,user_id uuid,display_name text,status text,role text);
create table job_roles(id uuid primary key,company_id uuid,status text default 'open');
create table candidate_applications(id uuid primary key,company_id uuid,job_id uuid,created_at timestamptz default now());
create table human_review_decisions(id uuid primary key,reason text);

create function demo_workspace_is_writable(p uuid) returns boolean language sql security definer as $$select writable from companies where id=p$$;
insert into companies values('${id(1)}','active',true),('${id(2)}','active',true);
insert into recruiter_profiles values('${id(11)}','${id(1)}','${id(101)}','Recruiter A','active','recruiter'),('${id(12)}','${id(2)}','${id(102)}','Recruiter B','active','recruiter'),('${id(13)}','${id(1)}','${id(103)}','Disabled','disabled','recruiter');
insert into job_roles(id,company_id) values('${id(21)}','${id(1)}'),('${id(22)}','${id(2)}');
insert into candidate_applications(id,company_id,job_id) values('${id(31)}','${id(1)}','${id(21)}'),('${id(32)}','${id(2)}','${id(22)}');
insert into human_review_decisions values('${id(41)}','Preserve this human decision');
select set_config('request.jwt.claim.sub','${id(101)}',false);`);
const membership=fs.readFileSync('supabase/migrations/202609090001_workspace_access_hardening.sql','utf8');
await db.exec(membership.slice(membership.indexOf('create or replace function public.current_company_ids()'),membership.indexOf('-- Storage policies')));
await db.exec(fs.readFileSync('supabase/migrations/202609190006_candidate_internal_notes.sql','utf8'));
const q=async(sql,args=[]) => (await db.query(sql,args)).rows;
const fail=async(sql,args,error)=>assert.rejects(()=>q(sql,args),e=>e.message.includes(error));
const create='select create_candidate_internal_note($1,$2,$3,$4) as result';
const edit='select update_candidate_internal_note($1,$2,$3,$4) as result';
await db.exec('set role authenticated');
assert.equal((await q('select list_candidate_internal_notes($1) as result',[id(31)]))[0].result.notes.length,0);
await fail(create,[id(32),'reviewer_observation','private',id(501)],'APPLICATION_UNAVAILABLE');
await fail(create,[id(31),'reviewer_observation','\t\n\r',id(501)],'NOTE_BODY_INVALID');
await fail(create,[id(31),'invalid','private',id(501)],'NOTE_KIND_INVALID');
await fail(create,[id(31),'reviewer_observation','   ',id(501)],'NOTE_BODY_INVALID');
await fail(create,[id(31),'reviewer_observation','x'.repeat(4001),id(501)],'NOTE_BODY_INVALID');
await fail(create,[id(31),'reviewer_observation','private',null],'NOTE_REQUEST_ID_REQUIRED');
let result=(await q(create,[id(31),'reviewer_observation',' Private <script>text</script> ',id(501)]))[0].result;
const noteId=result.id;
assert.equal(result.body,'Private <script>text</script>','literal plain text retained for escaped UI rendering');
assert.equal(result.author_name,'Recruiter A');
assert.equal(result.version,1);
assert.ok(!Object.hasOwn(result,'request_id'));
assert.equal((await q(create,[id(31),'reviewer_observation','Private <script>text</script>',id(501)]))[0].result.id,noteId);
await fail(create,[id(31),'reviewer_observation','different',id(501)],'NOTE_REQUEST_CONFLICT');
await fail(edit,[noteId,'candidate_statement','new',0],'NOTE_VERSION_CONFLICT');
assert.equal((await q(edit,[noteId,'candidate_statement','The candidate stated ownership of the project.',1]))[0].result.version,2);
assert.equal((await q(edit,[noteId,'candidate_statement','The candidate stated ownership of the project.',2]))[0].result.version,2);
assert.equal((await q(create,[id(31),'reviewer_observation','Private <script>text</script>',id(501)]))[0].result.version,2,'create retry after later edit returns current original note');
let events=(await q('select list_candidate_internal_note_events($1) as result',[noteId]))[0].result;
assert.equal(events.length,2);
assert.ok(events.every(e=>!Object.hasOwn(e.state,'request_id') && (!e.previous_state || !Object.hasOwn(e.previous_state,'request_id'))));
assert.ok((await q('select list_candidate_internal_notes($1) as result',[id(31)]))[0].result.notes.every(n=>!Object.hasOwn(n,'request_id')));
assert.ok(events.every(e=>e.actor_name==='Recruiter A'));
assert.equal(events.filter(e=>e.previous_state===null).length,1);
await fail('update candidate_internal_notes set body=$1',['forged'],'permission denied');
await fail('delete from candidate_internal_note_events',[],'permission denied');
await db.exec(`reset role; insert into recruiter_profiles values('${id(14)}','${id(1)}','${id(104)}','Company admin','active','admin'); select set_config('request.jwt.claim.sub','${id(104)}',false); set role authenticated;`);
assert.equal((await q('select list_candidate_internal_notes($1) as result',[id(31)]))[0].result.notes.length,1);
await fail(edit,[noteId,'verification_record','admin overwrite',2],'NOTE_AUTHOR_REQUIRED');
await fail(create,[id(31),'reviewer_observation','Private <script>text</script>',id(501)],'NOTE_REQUEST_CONFLICT');
await db.exec(`reset role; select set_config('request.jwt.claim.sub','${id(102)}',false); set role authenticated;`);
await fail('select list_candidate_internal_notes($1)',[id(31)],'APPLICATION_UNAVAILABLE');
await fail('select list_candidate_internal_note_events($1)',[noteId],'NOTE_UNAVAILABLE');
await fail(edit,[noteId,'reviewer_observation','foreign',2],'NOTE_UNAVAILABLE');
assert.equal((await q('select * from candidate_internal_notes')).length,0);
assert.equal((await q('select * from candidate_internal_note_events')).length,0);
await db.exec(`reset role; select set_config('request.jwt.claim.sub','${id(101)}',false); update companies set writable=null where id='${id(1)}'; set role authenticated;`);
assert.equal((await q('select list_candidate_internal_notes($1) as result',[id(31)]))[0].result.can_create,false);
await fail(create,[id(31),'reviewer_observation','private',id(502)],'NOTE_WRITE_ACCESS_REQUIRED');
await fail(edit,[noteId,'reviewer_observation','private',2],'NOTE_WRITE_ACCESS_REQUIRED');
await db.exec(`reset role; update recruiter_profiles set role='unsupported' where id='${id(11)}'; set role authenticated;`);
await fail('select list_candidate_internal_notes($1)',[id(31)],'APPLICATION_UNAVAILABLE');
await fail(create,[id(31),'reviewer_observation','private',id(502)],'APPLICATION_UNAVAILABLE');
await db.exec(`reset role; update recruiter_profiles set role='recruiter' where id='${id(11)}'; set role authenticated;`);
await db.exec(`reset role; update recruiter_profiles set status='disabled' where id='${id(11)}'; set role authenticated;`);
await fail('select list_candidate_internal_notes($1)',[id(31)],'APPLICATION_UNAVAILABLE');
await db.exec('reset role; set role anon');
await fail('select list_candidate_internal_notes($1)',[id(31)],'permission denied');
await fail(create,[id(31),'reviewer_observation','private',id(502)],'permission denied');
await db.exec(`reset role; delete from recruiter_profiles where id='${id(11)}';`);
assert.equal((await q('select author_profile_id from candidate_internal_notes'))[0].author_profile_id,null);
assert.ok((await q('select actor_name,actor_profile_id from candidate_internal_note_events')).every(e=>e.actor_name==='Recruiter A'&&e.actor_profile_id===null));
await db.exec(`delete from candidate_applications where id='${id(31)}'`);
assert.equal((await q('select * from candidate_internal_notes')).length,0);
assert.equal((await q('select * from candidate_internal_note_events')).length,0);
assert.equal((await q('select reason from human_review_decisions'))[0].reason,'Preserve this human decision');
await db.close();
console.log('Candidate internal notes PostgreSQL behavior passed: scoped access, author-only editing, idempotency, versioning, validation, attribution, entitlement and deletion.');
